var Benchmarks = map[string][]BenchmarkRule{
	"cis":  append(append(append([]BenchmarkRule{}, CISFortiOSRules...), CISIOSRules...), CISLinuxRules...),
	"nist": NISTRules,
	"pci":  PCIRules,
}

var BenchmarkTitles = map[string]string{
	"cis":  "CIS Benchmark (FortiGate 7.4.x / Cisco IOS XE 17.x / Ubuntu 24.04 LTS)",
	"nist": "NIST SP 800-53 Rev. 5",
	"pci":  "PCI-DSS v4.0",
}

func BenchmarkTitle(bm string) string {
	key := strings.ToLower(strings.TrimSpace(bm))
	if t, ok := BenchmarkTitles[key]; ok {
		return t
	}
	return "CIS Benchmark (FortiGate 7.4.x / Cisco IOS XE 17.x / Ubuntu 24.04 LTS)"
}

func renderEvidence(outcome RuleOutcome, lang string) []Evidence {
	var out []Evidence
	for _, e := range outcome.Evidence {
		text := e.Text
		if e.Message != "" {
			text = RenderMessage(e.Message, lang, e.Params)
		}
		out = append(out, Evidence{
			Line:    e.Line,
			Text:    text,
			Context: e.Context,
		})
	}
	return out
}

// RunNetSecAudit evaluates a configuration against the requested benchmark in the given language.
func RunNetSecAudit(configText, deviceName, benchmark, lang string) (AuditScanResult, error) {
	code := NormalizeLang(lang)
	bmKey := strings.ToLower(strings.TrimSpace(benchmark))
	if bmKey == "" || Benchmarks[bmKey] == nil {
		bmKey = "cis"
	}
	rulesList := Benchmarks[bmKey]

	vendor := DetectVendor(configText)
	var parsedCfg any
	parsedAnything := false

	if vendor == VendorIOS {
		cfg := ParseIOS(configText)
		parsedCfg = cfg
		parsedAnything = !cfg.IsEmpty()
	} else if vendor == VendorLinux {
		cfg := ParseLinux(configText)
		parsedCfg = cfg
		parsedAnything = !cfg.IsEmpty()
	} else {
		cfg := ParseWithLines(configText)
		parsedCfg = cfg
		parsedAnything = len(cfg.Records) > 0 || len(cfg.Sections) > 0
	}

	targetVendor := vendor
	if targetVendor == "" {
		targetVendor = VendorFortiOS
	}

	device := deviceName
	if device == "" {
		device = "-"
	}

	nothingOutcome := RuleOutcome{
		Status:  StatusUnknown,
		Message: "engine.nothing_to_assess",
	}

	var evaluated []RuleResult
	for _, tmpl := range rulesList {
		if tmpl.Vendor != targetVendor {
			continue
		}

		outcome := nothingOutcome
		if parsedAnything {
			outcome = tmpl.Check(parsedCfg)
		}

		title := tmpl.Title[code]
		if title == "" {
			title = tmpl.Title["it"]
		}

		remStr := ""
		if str, ok := tmpl.Remediation.(string); ok {
			remStr = str
		} else if m, ok := tmpl.Remediation.(map[string]string); ok {
			remStr = m[code]
			if remStr == "" {
				remStr = m["it"]
			}
		}

		evaluated = append(evaluated, RuleResult{
			ID:          tmpl.ID,
			Title:       title,
			Severity:    tmpl.Severity,
			Category:    tmpl.Category,
			Vendor:      tmpl.Vendor,
			Ref:         tmpl.Ref,
			Level:       tmpl.Level,
			Automated:   tmpl.Automated,
			AuditCLI:    tmpl.AuditCLI,
			Status:      outcome.Status,
			Device:      device,
			Detail:      RenderMessage(outcome.Message, code, outcome.Params),
			Remediation: remStr,
			Guidance:    GuidanceFor(tmpl.CheckName, code),
			Evidence:    renderEvidence(outcome, code),
		})
	}

	score, summary := CalculateScore(evaluated)
	grade := ScoreGrade(score)

	return AuditScanResult{
		DeviceName:     device,
		Benchmark:      bmKey,
		BenchmarkTitle: BenchmarkTitle(bmKey),
		Vendor:         vendor,
		Lang:           code,
		Score:          score,
		Grade:          grade,
		Summary:        summary,
		Rules:          evaluated,
	}, nil
}
